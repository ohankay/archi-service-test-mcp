"""Test generators of the test approaches. Deterministic: same operation definition -> same table.

* ``boundary_value``  boundary values of every limited input (min / max, and the date range rule)
* ``equivalence``     one representative of each equivalence class (valid options, invalid option, past/today/future)
* ``negative``        required inputs left out, wrong types sent as they are
* ``pairwise``        every pair of input values covered at least once (greedy all-pairs)
* ``agent``           no code: the approach's rules are handed to the agent, which writes the table itself

The result is a draft table test (``status: draft``). Expected results come from the definition (inside a limit ->
success, outside -> the approach's ``expected_outside``); what the definition can not tell is ``?`` and is reported
as an observation for a person to confirm.
"""

from __future__ import annotations

import datetime as _dt
from decimal import Decimal
from typing import Any

from .store import DefinitionError, Record, Store
from .values import day_expression, day_text

DEFAULT_LIMIT = 40


def _offset(expr: Any) -> int | None:
    """'today-30' -> -30 (days from today), else None."""
    day = day_expression(expr)
    return None if day is None else (day - _dt.date.today()).days


def _step(kind: str) -> Decimal:
    return Decimal("0.01") if kind == "decimal" else Decimal(1)


def _number(value: Any) -> Decimal | None:
    try:
        return Decimal(str(value))
    except Exception:  # noqa: BLE001
        return None


def _out(value: Decimal, kind: str) -> Any:
    return int(value) if kind == "integer" else str(value)


class Generator:
    def __init__(self, store: Store) -> None:
        self.store = store

    def generate(self, approach: str, operation: str, common_input: dict[str, Any] | None = None) -> dict[str, Any]:
        ap = self.store.get("approach", approach)
        op = self.store.get("operation", operation)
        generator = ap.data["generator"]
        notes: list[str] = []
        if generator == "agent":
            return {"generated_by": "agent", "approach": ap.name, "operation": op.name,
                    "rules": ap.data.get("rules") or [], "inputs": op.data.get("inputs") or {},
                    "instruction": "This approach is not generated by code. Write a table test (operation + "
                                   "examples) by the rules, put '?' as expected where you do not know the result, "
                                   "show it to the user and save it with save_definition when approved."}
        rows = _unique(getattr(self, f"_{generator}")(op, ap, notes))
        limit = int(ap.data.get("limit") or DEFAULT_LIMIT)
        if len(rows) > limit:
            notes.append(f"{len(rows)} cases generated, the approach's limit is {limit}: the first {limit} kept")
            rows = rows[:limit]
        if not rows:
            raise DefinitionError([f"no '{ap.name}' cases for '{op.name}': " + ("; ".join(notes) or
                                                                              "not enough input information")])
        test: dict[str, Any] = {"name": f"{op.name} - {ap.name}",
                                "description": f"Generated with the '{ap.name}' approach.",
                                "status": "draft", "approach": ap.name, "generated_by": "code", "operation": op.name}
        if common_input:
            test["common_input"] = common_input
        test["examples"] = rows
        return {"test": test, "notes": notes, "unknown_expected": sum(1 for r in rows if r["expected"] == "?")}

    # -- generators ----------------------------------------------------------------------------------------------
    def _boundary_value(self, op: Record, ap: Record, notes: list[str]) -> list[dict[str, Any]]:
        outside = ap.data.get("expected_outside", "error")
        rows: list[dict[str, Any]] = []
        for name, spec in (op.data.get("inputs") or {}).items():
            kind = spec.get("type") or "text"
            lo, hi = spec.get("min"), spec.get("max")
            if lo is None and hi is None:
                continue
            if kind in ("integer", "decimal"):
                step = _step(kind)
                for label, bound, sign in (("min", lo, -1), ("max", hi, 1)):
                    b = _number(bound)
                    if b is None:
                        continue
                    rows += [{"case": f"{name}: {label}{'-' if sign < 0 else '+'}1 (outside)",
                              name: _out(b + sign * step, kind), "expected": outside},
                             {"case": f"{name}: {label} ({_out(b, kind)})", name: _out(b, kind), "expected": "success"},
                             {"case": f"{name}: {label}{'+' if sign < 0 else '-'}1", name: _out(b - sign * step, kind),
                              "expected": "success"}]
            elif kind == "date":
                for label, bound, sign in (("earliest", lo, -1), ("latest", hi, 1)):
                    off = _offset(bound)
                    if off is None:
                        continue
                    rows += [{"case": f"{name}: {label} - 1 day outside", name: day_text(off + sign),
                              "expected": outside},
                             {"case": f"{name}: {label}", name: day_text(off), "expected": "success"}]
            elif kind == "text":
                for label, bound, sign in (("shortest", lo, -1), ("longest", hi, 1)):
                    n = _number(bound)
                    if n is None:
                        continue
                    n = int(n)
                    if n + sign >= 0:
                        rows.append({"case": f"{name}: {label} {n + sign} characters (outside)",
                                     name: "a" * (n + sign), "expected": outside})
                    rows.append({"case": f"{name}: {label} {n} characters", name: "a" * n, "expected": "success"})
        date_range = op.data.get("date_range")
        if date_range:
            s, e = date_range["start"], date_range["end"]
            rows += [{"case": "same day (0 days)", s: "today", e: "today", "expected": "success"},
                     {"case": "end one day before start", s: "today", e: "today-1", "expected": outside}]
            n = date_range.get("max_days")
            if n is not None:
                rows += [{"case": f"exactly {n} days", s: day_text(-n), e: "today", "expected": "success"},
                         {"case": f"{n + 1} days (outside)", s: day_text(-n - 1), e: "today", "expected": outside}]
            else:
                notes.append("the longest allowed date range is not defined (date_range.max_days)")
            rows.append({"case": "end date in the future", s: "today", e: "today+1", "expected": "?"})
        if not rows:
            notes.append(f"the inputs of '{op.name}' have no limits: add min / max or date_range "
                         "(or find the limits with exploratory calls and suggest them)")
        return rows

    def _equivalence(self, op: Record, ap: Record, notes: list[str]) -> list[dict[str, Any]]:
        outside = ap.data.get("expected_outside", "error")
        rows: list[dict[str, Any]] = []
        date_range = op.data.get("date_range") or {}
        in_range = {date_range.get("start"), date_range.get("end")}
        for name, spec in (op.data.get("inputs") or {}).items():
            kind = spec.get("type") or "text"
            if kind == "date" and name in in_range:
                continue                     # classified together, as a range (below)
            if kind == "list":
                rows += [{"case": f"{name} = {o}", name: o, "expected": "success"} for o in spec.get("options") or []]
                rows.append({"case": f"{name}: value not in the list", name: {"raw": "INVALID"}, "expected": outside})
            elif kind == "boolean":
                rows += [{"case": f"{name} = true", name: True, "expected": "success"},
                         {"case": f"{name} = false", name: False, "expected": "success"}]
            elif kind in ("integer", "decimal"):
                lo, hi = _number(spec.get("min")), _number(spec.get("max"))
                if lo is not None and hi is not None:
                    rows.append({"case": f"{name}: inside the range", name: _out((lo + hi) / 2 if kind == "decimal"
                                                                                  else (lo + hi) // 2, kind),
                                 "expected": "success"})
                elif lo is not None:
                    rows.append({"case": f"{name}: inside the range", name: _out(lo + 1, kind), "expected": "success"})
                if lo is not None:
                    rows.append({"case": f"{name}: below min", name: _out(lo - 10, kind), "expected": outside})
                if hi is not None:
                    rows.append({"case": f"{name}: above max", name: _out(hi + 10, kind), "expected": outside})
                if lo is None and hi is None:
                    rows += [{"case": f"{name}: zero", name: 0, "expected": "?"},
                             {"case": f"{name}: negative", name: -1, "expected": "?"}]
            elif kind == "date":
                rows += [{"case": f"{name}: past", name: "today-10", "expected": "success"},
                         {"case": f"{name}: today", name: "today", "expected": "success"},
                         {"case": f"{name}: future", name: "today+10", "expected": "?"}]
            else:
                rows.append({"case": f"{name}: empty text", name: "",
                             "expected": outside if spec.get("required") else "?"})
        if date_range:
            s, e = date_range["start"], date_range["end"]
            rows += [{"case": "range: last 7 days", s: "today-7", e: "today", "expected": "success"},
                     {"case": "range: all in the past", s: "today-60", e: "today-30", "expected": "success"},
                     {"case": "range: reversed (end first)", s: "today", e: "today-7", "expected": outside},
                     {"case": "range: in the future", s: "today+1", e: "today+10", "expected": "?"}]
        if not rows:
            notes.append(f"operation '{op.name}' has no input to classify")
        return rows

    def _negative(self, op: Record, ap: Record, notes: list[str]) -> list[dict[str, Any]]:
        outside = ap.data.get("expected_outside", "error")
        rows: list[dict[str, Any]] = []
        for name, spec in (op.data.get("inputs") or {}).items():
            if spec.get("required"):
                rows.append({"case": f"{name} not sent", name: None, "expected": outside})
            kind = spec.get("type") or "text"
            if kind in ("integer", "decimal"):
                rows.append({"case": f"{name}: text instead of a number", name: {"raw": "abc"}, "expected": outside})
            elif kind == "date":
                rows.append({"case": f"{name}: invalid date", name: {"raw": "31.02.2026"}, "expected": outside})
                rows.append({"case": f"{name}: wrong format", name: {"raw": "2026-13-45"}, "expected": outside})
        if not rows:
            notes.append(f"operation '{op.name}' has no required or typed input")
        return rows

    def _pairwise(self, op: Record, ap: Record, notes: list[str]) -> list[dict[str, Any]]:
        params: list[tuple[str, list[Any]]] = []
        for name, spec in (op.data.get("inputs") or {}).items():
            kind = spec.get("type") or "text"
            if kind == "list" and spec.get("options"):
                params.append((name, list(spec["options"])))
            elif kind == "boolean":
                params.append((name, [True, False]))
            elif kind in ("integer", "decimal") and spec.get("min") is not None and spec.get("max") is not None:
                lo, hi = _number(spec["min"]), _number(spec["max"])
                params.append((name, sorted({_out(lo, kind), _out(hi, kind)}, key=str)))  # type: ignore[arg-type]
        if len(params) < 2:
            notes.append("pairwise needs at least two inputs with a known set of values (list, boolean, or a "
                         "number with min and max)")
            return []
        combos = all_pairs([vals for _, vals in params])
        names = [name for name, _ in params]
        notes.append(f"{len(params)} inputs: every value pair covered with {len(combos)} combinations "
                     f"(all combinations: {_product([len(v) for _, v in params])})")
        return [{"case": ", ".join(f"{n}={v}" for n, v in zip(names, combo, strict=True)),
                 **dict(zip(names, combo, strict=True)), "expected": "success"} for combo in combos]


def _product(sizes: list[int]) -> int:
    out = 1
    for s in sizes:
        out *= s
    return out


def all_pairs(values: list[list[Any]]) -> list[tuple[Any, ...]]:
    """Greedy all-pairs: rows so that every value pair of every two parameters appears at least once."""
    n = len(values)
    uncovered = {(i, a, j, b) for i in range(n) for j in range(i + 1, n)
                 for a in range(len(values[i])) for b in range(len(values[j]))}
    rows: list[tuple[int, ...]] = []
    while uncovered:
        i0, a0, j0, b0 = min(uncovered)
        row: list[int | None] = [None] * n
        row[i0], row[j0] = a0, b0
        for k in range(n):
            if row[k] is not None:
                continue
            best, best_score = 0, -1
            for v in range(len(values[k])):
                score = sum(1 for m in range(n) if row[m] is not None and
                            ((min(k, m), v if k < m else row[m], max(k, m), row[m] if k < m else v) in uncovered))
                if score > best_score:
                    best, best_score = v, score
            row[k] = best
        full = tuple(int(x) for x in row)  # type: ignore[arg-type]
        for i in range(n):
            for j in range(i + 1, n):
                uncovered.discard((i, full[i], j, full[j]))
        rows.append(full)
    return [tuple(values[i][r[i]] for i in range(n)) for r in rows]


def _unique(rows: list[dict[str, Any]]) -> list[dict[str, Any]]:
    seen, out = set(), []
    for row in rows:
        key = repr(sorted((k, repr(v)) for k, v in row.items() if k != "case"))
        if key not in seen:
            seen.add(key)
            out.append(row)
    return out
